    let name = KNOWN_BUILDING_NAMES[id] || id.split('_').map(word => word.charAt(0).toUpperCase() + word.slice(1)).join(' ');

    // Calculate center coordinates of the polygon for navigation
    const polyCoords = f.geometry.coordinates[0];
    let lngSum = 0, latSum = 0;
    polyCoords.forEach(c => { lngSum += c[0]; latSum += c[1]; });
    const centerCoords = CUSTOM_BUILDING_CENTERS[id] || [lngSum / polyCoords.length, latSum / polyCoords.length];

    return {
        id: id,
        name: name,
        icon: '🏢',
        desc: 'DA-LARES Facility',
        section: 'Compound',
        coords: centerCoords,
        color: '#3b82f6'
    };
